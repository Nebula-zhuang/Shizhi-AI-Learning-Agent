def build_pdf(
    sections: list[tuple[str, list[str]]],
    *,
    header: str,
    footer: str,
    cover_title: str,
    cover_subtitle: str,
) -> bytes:
    """把章节内容排成一份带页眉页脚的 PDF。

    生成要点（与 P1 解析器的能力对齐）：
      - 必须嵌入 CJK 字体，否则中文提取出来是乱码
      - 页眉每页相同、页脚逐页变化 → 验证解析器的重复内容剔除
      - 小节标题用大字号 → 验证标题识别与章节层级推导
      - 每页放一个小节标题，保证章节边界干净、图谱分带清楚
    """
    import pymupdf

    doc = pymupdf.open()
    page_width, page_height = 595, 842
    margin = 72
    body_font_size = 11
    line_height = 21

    cjk_font = pymupdf.Font("china-s")
    font_name = "F0"

    # ---------------------------------------------------------------- 封面
    cover = doc.new_page(width=page_width, height=page_height)
    cover.insert_font(fontname=font_name, fontbuffer=cjk_font.buffer)
    cover.insert_text(
        (margin, 300), cover_title, fontname=font_name, fontsize=24, color=(0.1, 0.1, 0.1)
    )
    cover.insert_text(
        (margin, 340), cover_subtitle, fontname=font_name, fontsize=13, color=(0.35, 0.35, 0.35)
    )

    # ------------------------------------------------------- 每个小节一页
    for index, (title, paragraphs) in enumerate(sections, start=1):
        page = doc.new_page(width=page_width, height=page_height)
        page.insert_font(fontname=font_name, fontbuffer=cjk_font.buffer)

        page.insert_text(
            (margin, 45), header, fontname=font_name, fontsize=9, color=(0.45, 0.45, 0.45)
        )
        page.insert_text(
            (page_width / 2 - 30, page_height - 35),
            f"{footer} · 第 {index} 页",
            fontname=font_name,
            fontsize=9,
            color=(0.45, 0.45, 0.45),
        )

        y = margin + 24
        page.insert_text((margin, y), title, fontname=font_name, fontsize=16)
        y += 40

        for paragraph in paragraphs:
            line = ""
            for char in paragraph:
                line += char
                if len(line) >= 34:
                    page.insert_text(
                        (margin, y), line, fontname=font_name, fontsize=body_font_size
                    )
                    y += line_height
                    line = ""
            if line:
                page.insert_text(
                    (margin, y), line, fontname=font_name, fontsize=body_font_size
                )
                y += line_height
            y += 12

    # 字体子集化：`insert_font` 是把整份 CJK 字体嵌进**每一页**，
    # 不做子集化的话一份 7 页的讲义就有 3.5 MB —— 演示时上传慢，也没必要。
    # subset_fonts() 只保留实际用到的字形，能压到几十 KB。
    doc.subset_fonts()
    return doc.tobytes()


